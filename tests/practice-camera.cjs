const {chromium}=require('playwright'),assert=require('assert');
(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true,args:['--enable-unsafe-swiftshader']});
 try{
  const page=await browser.newPage({viewport:{width:1600,height:1000}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:8765');
  await page.waitForFunction(()=>document.querySelector('#connection').textContent.includes('connected'));
  assert.equal(await page.locator('#quickCamera').inputValue(),'orbit','Practice opens with free camera');
  await page.waitForFunction(()=>document.querySelector('#clock').textContent==='FREE');
  await page.evaluate(async()=>{const {FieldView}=await import('/render.js');const original=FieldView.prototype.updateCamera;FieldView.prototype.updateCamera=function(dt){window.cameraTestView=this;return original.call(this,dt);};});
  await page.waitForFunction(()=>window.cameraTestView);
  await page.locator('#quickCamera').selectOption('orbit');
  await page.locator('[data-panel="view"]').click();
  assert(await page.locator('#freeCameraControls').isVisible());
  assert(await page.locator('#driverCameraControls').isHidden());
  let initial=await page.evaluate(()=>cameraTestView.camera.position.toArray());
  await page.getByRole('button',{name:'Right',exact:true}).click();
  let moved=await page.evaluate(()=>cameraTestView.camera.position.toArray());
  assert(Math.hypot(...moved.map((n,i)=>n-initial[i]))>.45,'Camera movement button moves viewpoint');
  await page.getByText('Exact camera position',{exact:true}).click();
  for(const[id,value]of [['cameraX','2.5'],['cameraY','1.25'],['cameraZ','-3.5']])await page.locator('#'+id).fill(value);
  await page.locator('#placeCamera').click();
  let pose=await page.evaluate(()=>({eye:cameraTestView.camera.position.toArray(),target:cameraTestView.controls.target.toArray()}));
  pose.eye.forEach((n,i)=>assert(Math.abs(n-[2.5,1.25,-3.5][i])<1e-6,'Exact viewpoint can be anywhere around the field'));
  await page.locator('[data-panel="drive"]').click();
  await page.locator('#mode').selectOption('match-teleop');
  await page.waitForFunction(()=>document.querySelector('#quickCamera option[value=orbit]').disabled);
  assert(['red','blue'].includes(await page.locator('#quickCamera').inputValue()));
  await page.evaluate(()=>cameraTestView.moveCamera(10,10,10));
  let match=await page.evaluate(()=>cameraTestView.camera.position.toArray());
  assert(Math.abs(Math.abs(match[0])-(72*.0254+.68))<1e-6,'Match stays at alliance station');
  await page.locator('#mode').selectOption('practice');
  await page.waitForFunction(()=>document.querySelector('#quickCamera').value==='orbit');
  let restored=await page.evaluate(()=>({eye:cameraTestView.camera.position.toArray(),target:cameraTestView.controls.target.toArray()}));
  restored.eye.forEach((n,i)=>assert(Math.abs(n-pose.eye[i])<1e-6,'Practice position restored'));
  restored.target.forEach((n,i)=>assert(Math.abs(n-pose.target[i])<1e-6,'Practice aim restored'));
  // Pan with the mouse in the field, away from the controls.
  await page.mouse.move(800,500);await page.mouse.down({button:'right'});await page.mouse.move(900,540,{steps:8});await page.mouse.up({button:'right'});
  let panned=await page.evaluate(()=>cameraTestView.camera.position.toArray());
  assert(Math.hypot(...panned.map((n,i)=>n-restored.eye[i]))>.05,'Right drag pans freely');
  await page.locator('#focusRobot').click();
  let centered=await page.evaluate(()=>({target:cameraTestView.controls.target.toArray(),robot:cameraTestView.robot.position.toArray()}));
  assert(Math.abs(centered.target[0]-centered.robot[0])<.03&&Math.abs(centered.target[2]-centered.robot[2])<.03,'Find robot centers its current area while the chassis settles');
  await page.locator('#init').click();await page.waitForFunction(()=>document.querySelector('#phase').textContent==='INITIALIZED');
  assert((await page.locator('#runGuide').textContent()).includes('Press Start'));
  await page.locator('#start').click();await page.waitForFunction(()=>document.querySelector('#phase').textContent==='RUNNING');
  await page.locator('#quickStop').click();await page.waitForFunction(()=>document.querySelector('#phase').textContent==='STOPPED');
  await page.locator('#closeControls').click();assert(await page.locator('#drawer').isHidden());
  await page.locator('#showControls').click();assert(await page.locator('#drawer').isVisible());
  await page.screenshot({path:'../output/practice-ui-desktop.png'});
  await page.setViewportSize({width:390,height:844});
  await page.locator('#closeControls').click();
  await page.screenshot({path:'../output/practice-ui-mobile.png'});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'No horizontal page overflow');
  assert.deepEqual(errors,[],'No browser errors');
  console.log('PASS: free-camera controls/position/pan/focus, match restrictions, practice pose restoration, guided run/stop, drawer controls and mobile layout');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1)});
